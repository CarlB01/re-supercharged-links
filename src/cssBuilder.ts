import { CSSLink, matchSign } from "./cssLink";
import ResuperchargedLinks from "./main";

// En 2D-matrise (tabell) som inneholder 6 rader, der hver rad har 6 HEX-fargekoder.
const colorSet = [[
    '#0089BA', '#2C73D2', '#008E9B', '#0081CF', '#008F7A', '#008E9B',
], [
    '#D65DB1', '#0082C1', '#9270D3', '#007F93', '#007ED9', '#007660',
], [
    '#FF9671', '#A36AAA', '#F27D88', '#6967A9', '#D26F9D', '#1b6299',
], [
    '#FFC75F', '#4C9A52', '#C3BB4E', '#00855B', '#88AC4B', '#006F61',
], [
    '#FF6F91', '#6F7F22', '#E07250', '#257A3E', '#AC7C26', '#006F5F',
], [
    '#d9d867', '#2FAB63', '#B8E067', '#008E63', '#78C664', '#007160',
]];

// Her skal alle fargene samles i én eneste lang, flat liste (string-array)
const colors: string[] = [];

// Denne doble løkken sorterer fargene på en spesiell måte: vertikalt (kolonne for kolonne).
// Den ytre løkken ('i') bestemmer hvilken kolonne-indeks (0 til 5) vi ser på.
for (const i of Array(6).keys()) {
    // Den indre løkken ('j') går gjennom hver rad (0 til 5).
    for (const j of Array(6).keys()) {
        // Henter fargen fra rad 'j', kolonne 'i'. 
        // Ved å bruke `?.[i]` kræsjer ikke koden hvis en rad skulle mangle en indeks.
        const color = colorSet[j]?.[i]; 
        
        // Sjekker at vi faktisk fant en fargekode (at den ikke er undefined)
        if (color !== undefined) {
            colors.push(color); // Legger fargen til i den flate 'colors'-listen
        }
    }
}

/**
 * En hash-funksjon (basert på DJB2-algoritmen).
 * Den tar inn en tekst-streng (som en uid) og gjør den om til et unikt, positivt heltall.
 * Dette tallet brukes ofte til å velge en tilfeldig, men FAST farge fra en liste (f.eks: colors[hash % colors.length]).
 */
function hash(uid: string) {
    let hash = 0; // Startverdi for hashen
    
    // Går gjennom hvert enkelt tegn i 'uid'-strengen, ett etter ett
    for (let i = 0; i < uid.length; i++) {
        const char = uid.charCodeAt(i); // Henter den numeriske datakoden (ASCII/Unicode) for tegnet
        
        // Avansert bit-manipulasjon for å blande verdiene sammen. 
        // `hash << 5` Ganger den nåværende hashen med 32, trekker fra seg selv, og legger til det nye tegnet.
        hash = ((hash << 5) - hash) + char;
        
        // Tvinger tallet til å holde seg innenfor rammen av et standard 32-bit heltall (bitvis AND)
        hash = hash & hash; 
    }
    
    // Sørger for at tallet alltid blir positivt (fjerner eventuelle minustegn)
    hash = Math.abs(hash);
    
    return hash; // Returnerer det ferdige tallet (f.eks. 4829103)
}

/**
 * Denne funksjonen bygger en komplett CSS-fil (supercharged-links-gen.css) dynamisk. 
 * CSS-filen inneholder både selve stilene (farger/ikoner) og en spesiell kommentarseksjon nederst
 *  (/* @settings ... Det er denne kommentarseksjonen Style Settings-pluginet leser 
 * for å lage brukergrensesnittet sitt!
 */
export async function buildCSS(selectors: CSSLink[], plugin: ResuperchargedLinks) {
    // 1. STARTER PÅ FILEN: Lager en liste med tekstlinjer og legger til en advarsel øverst.
    const instructions: string[] = [
        "/* WARNING: This file will be overwritten by the plugin.",
        "Do not edit this file directly! First copy this file and rename it if you want to edit things. */",
        "",
        ":root {" // Åpner :root for å definere globale CSS-variabler
    ];

    // 2. CSS-VARIABLER: Går gjennom alle valgene og lager standard CSS-variabler i :root.
    // Det er her den forrige funksjonen bruker hash(uid) % 36 til å gi hver UID en unik farge.
    selectors.forEach((selector, i) => {
        if (selector.selectText) {
            instructions.push(`    --${selector.uid}-color: ${colors[hash(selector.uid) % 36]};`);
            instructions.push(`    --${selector.uid}-weight: initial;`);
        }
        if (selector.selectPrepend) {
            instructions.push(`    --${selector.uid}-before: '';`);
        }
        if (selector.selectAppend) {
            instructions.push(`    --${selector.uid}-after: '';`);
        }
        if (selector.selectBackground) {
            instructions.push(`    --${selector.uid}-background-color: #ffffff;`);
            instructions.push(`    --${selector.uid}-decoration: initial;`);
        }
    });
    instructions.push("}"); // Lukker :root {}

    // 3. SELEKTORER: Genererer de faktiske CSS-reglene for hvordan lenkene skal styles i Obsidian.
    selectors.forEach(selector => {
        let cssSelector: string;
        
        // Sjekker om lenken matches basert på egenskap (attribute), tag eller filbane (path).
        if (selector.type === 'attribute') {
            cssSelector = `[data-link-${selector.name}${matchSign[selector.match]}="${selector.value}" ${selector.matchCaseSensitive ?"" : " i"}]`;
        }
        else if (selector.type === 'tag') {
            cssSelector = `[data-link-tags*="${selector.value}" i]`;
        }
        else {
            cssSelector = `[data-link-path${matchSign[selector.match]}="${selector.value}" ${selector.matchCaseSensitive ?"" : "i"}]`;
        }

        // Legger til CSS-regler for tekstfarge hvis det er valgt
        if (selector.selectText) {
            instructions.push(...[
                "",
                `div[data-id="${selector.uid}"] div.setting-item-description,`,
                cssSelector + " {",
                `    color: var(--${selector.uid}-color) !important;`,
                `    font-weight: var(--${selector.uid}-weight);`,
                "}"]);
        }
        // Legger til CSS for bakgrunnsfarge
        if (selector.selectBackground) {
            instructions.push(...["",
                `.c-${selector.uid}-use-background div[data-id="${selector.uid}"] div.setting-item-description,`,
                `.c-${selector.uid}-use-background .data-link-text${cssSelector} {`,
                `    background-color: var(--${selector.uid}-background-color) !important;`,
                `    border-radius: 5px;`,
                `    padding-left: 2px;`,
                `    padding-right: 2px;`,
                `    text-decoration: var(--${selector.uid}-decoration) !important;`,
                "}"]);
        }
        // Legger til CSS for tekst/ikon *før* lenken (Prepend)
        if (selector.selectPrepend) {
            instructions.push(...["",
                `div[data-id="${selector.uid}"] div.setting-item-description::before,`,
                `.data-link-icon${cssSelector}::before {`,
                `    content: var(--${selector.uid}-before);`,
                "}"]);
        }
        // Legger til CSS for tekst/ikon *etter* lenken (Append)
        if (selector.selectAppend) {
            instructions.push(...["",
                `div[data-id="${selector.uid}"] div.setting-item-description::after,`,
                `.data-link-icon-after${cssSelector}::after {`,
                `    content: var(--${selector.uid}-after);`,
                "}"]);
        }
    });

    // 4. STYLE SETTINGS KONFIGURASJON: Begynner på den magiske kommentaren som 'Style Settings'-pluginet leser.
    instructions.push(...[
        "/* @settings",
        "name: Supercharged Links",
        "id: supercharged-links",
        "settings:",
    ]);

    // Går gjennom alle selektorer på nytt for å bygge kontrollpanelet (GUI-en) i Style Settings
    selectors.forEach((selector, i) => {
        let name = selector.name;
        let value = selector.value;
        if (selector.type === 'tag') { name = 'tag'; }
        else if (selector.type === 'path'){ name = 'path'; }
        
        // Lager en overskrift (heading) i Style Settings-menyen for denne spesifikke lenke-regelen
        instructions.push(...[
            "    - ",
            `        id: ${selector.uid}`, // ⚠️ DETTE ER SVÆRT VIKTIG FOR FEILEN DIN
            `        title: ${name} is ${value}`,
            `        description: Example note`,
            "        type: heading",
            "        collapsed: true",
            "        level: 3"]);
            
        // Hvis tekstfarge er aktivert, fortell Style Settings at den skal vise en fargevelger (variable-color)
        if (selector.selectText) {
            instructions.push(...[
                "    - ",
                `        id: ${selector.uid}-color`, // Kobler fargevelgeren til CSS-variabelen
                `        title: Link color`,
                "        type: variable-color", // Dette ber Style Settings (via Pickr) om å åpne en fargevelger
                "        format: hex",
                `        default: '${colors[hash(selector.uid) % 36]}'`, // Standard fargekode (f.eks '#0089BA')
                "    - ",
                // ... (Fontvekt- og dekorasjonsmenyer)
                `        id: ${selector.uid}-weight`,
                `        title: Font weight`,
                "        type: variable-select",
                `        default: initial`,
                `        options: [initial, lighter, normal, bold, bolder]`,
                "    - ",
                `        id: ${selector.uid}-decoration`,
                `        title: Font decoration`,
                "        type: variable-select",
                `        default: initial`,
                `        options: [initial, underline, overline, line-through]`])
        }
        // Hvis Prepend (Ikon/tekst før) er valgt, lag et tekstfelt i Style Settings
        if (selector.selectPrepend) {
            instructions.push(...["    - ",
            `        id: ${selector.uid}-before`,
            `        title: Prepend text`,
            `        description: Add some text, such as an emoji, before the links.`,
            "        type: variable-text",
            `        default: ''`,
            `        quotes: true`])
        }
        // ... (Tilsvarende for Append og Bakgrunnsfarge)
        if (selector.selectAppend) {
            instructions.push(...["    - ",
                `        id: ${selector.uid}-after`,
                `        title: Append text`,
                `        description: Add some text, such as an emoji, after the links.`,
                "        type: variable-text",
                `        default: ''`,
                `        quotes: true`])
        }
        if(selector.selectBackground) {
            instructions.push(...["    - ",
                `        id: c-${selector.uid}-use-background`,
                `        title: Use background color`,
                `        description: Adds a background color to the link. This can look buggy in live preview.`,
                "        type: class-toggle",
                "    - ",
                `        id: ${selector.uid}-background-color`,
                `        title: Background color`,
                "        type: variable-color",
                "        format: hex",
                `        default: '#ffffff'`])
        }
    });
    instructions.push("*/"); // Avslutter Style Settings-kommentaren

    // 5. LAGRE FILEN: Skriver hele tekstmassen til `.obsidian/snippets/supercharged-links-gen.css`
    const vault = plugin.app.vault;
    const configDir = vault.configDir ?? ".obsidian";
    const pathDir = configDir + "/snippets";
    await vault.adapter.mkdir(pathDir);
    const path = pathDir + "/supercharged-links-gen.css";
    if (await vault.adapter.exists(path)) {
        await vault.adapter.remove(path);
    }
    await plugin.app.vault.create(path, instructions.join('\n'));

    // 6. AKTIVER CSS-SNIPPET: Sier ifra til Obsidian at den nye CSS-filen må skrus på og lastes inn.
    if (plugin.settings.activateSnippet) {
        // @ts-ignore
        const customCss = plugin.app.customCss;
        customCss.enabledSnippets.add('supercharged-links-gen');
        customCss.requestLoadSnippets();
    }

    // 7. OPPDATER STYLE SETTINGS: Sender en beskjed (event) i Obsidian om at Style Settings må lese inn filen på nytt.
    plugin.app.workspace.trigger("parse-style-settings");
}

